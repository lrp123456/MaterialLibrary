function loadOfficialSnippets() {
  const map = { ...FALLBACK_PROMPT_SNIPPETS };
  const candidatePaths = [
    path.resolve(__dirname, '../../../snippets.json'),
    path.resolve(__dirname, '../../snippets.json'),
  ];
  for (const p of candidatePaths) {
    try {
      if (fs.existsSync(p)) {
        const parsed = JSON.parse(fs.readFileSync(p, 'utf8'));
        if (Array.isArray(parsed)) {
          for (const item of parsed) {
            if (item && item.id) {
              map[item.id] = {
                ...map[item.id],
                ...item,
                is_builtin: item.is_builtin ?? 1,
                enabled: item.enabled ?? 1,
              };
            }
          }
        }
        break;
      }
    } catch (_) {}
  }
  return map;
}

