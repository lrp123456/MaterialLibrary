// ★ 对外统一只保留一套下划线算子 ID：id === type === code
const OPERATOR_CATALOG = RAW_OPERATOR_CATALOG.map(({ legacyCode, ...op }) => ({
  ...op,
  id: op.type,
  code: op.type,
}));

// 内部兼容查找映射（对外统一展示下划线 type，但内部 getOperatorSpec 仍兼容旧别名查询）
const OPERATOR_MAP = new Map();
RAW_OPERATOR_CATALOG.forEach((rawOp, idx) => {
  const canonical = OPERATOR_CATALOG[idx];
  OPERATOR_MAP.set(canonical.type, canonical);
  if (rawOp.legacyCode) OPERATOR_MAP.set(rawOp.legacyCode, canonical);
});
OPERATOR_MAP.set('qc', OPERATOR_MAP.get('script_qc'));
OPERATOR_MAP.set('clean', OPERATOR_MAP.get('edit_clean'));
OPERATOR_MAP.set('video.ffmpeg_slice', OPERATOR_MAP.get('video_slice'));
OPERATOR_MAP.set('video.ffmpeg_keyframes', OPERATOR_MAP.get('video_extract_frames'));

function getOperatorCatalog() {
  return OPERATOR_CATALOG;
}

function getOperatorSpec(typeOrCode) {
  return OPERATOR_MAP.get(String(typeOrCode || '').trim()) || null;
}

