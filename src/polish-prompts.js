function officialPolish(modelId) {
  const id = String(modelId || '')
  try {
    const { loadSkillForModel } = require('./skill-loader')
    const fromSkill = loadSkillForModel(id)
    if (fromSkill) return fromSkill
  } catch (_) {}
  if (POLISH_PROMPTS[id]) return POLISH_PROMPTS[id]
  return null
}

