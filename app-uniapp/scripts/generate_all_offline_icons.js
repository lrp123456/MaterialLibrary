const COLOR_VARIANTS = [
  { suffix: '', color: '#475569' },       // default gray
  { suffix: '_dark', color: '#0F172A' },  // dark slate-900
  { suffix: '_blue', color: '#2563EB' },  // brand primary blue
  { suffix: '_white', color: '#FFFFFF' }, // pure white
  { suffix: '_orange', color: '#F97316' },// accent orange
  { suffix: '_red', color: '#EF4444' }    // danger red
];

const outDir = path.resolve(__dirname, '../src/static/icons');
if (!fs.existsSync(outDir)) {
  fs.mkdirSync(outDir, { recursive: true });
}

let svgCount = 0;
let pngCount = 0;

for (const [name, pathBody] of Object.entries(ICONS)) {
  for (const { suffix, color } of COLOR_VARIANTS) {
    const svgContent = `<svg xmlns="http://www.w3.org/2000/svg" width="24" height="24" viewBox="0 0 24 24" fill="none" stroke="${color}" stroke-width="2" stroke-linecap="round" stroke-linejoin="round">\n  ${pathBody}\n</svg>\n`;
    
    // Write SVG
    const svgFileName = `${name}${suffix}.svg`;
    fs.writeFileSync(path.join(outDir, svgFileName), svgContent, 'utf8');
    svgCount++;

    // Write PNG (96x96 for 4x crisp retina)
    const pngFileName = `${name}${suffix}.png`;
    const resvg = new Resvg(svgContent, {
      fitTo: { mode: 'width', value: 96 }
    });
    const pngBuffer = resvg.render().asPng();
    fs.writeFileSync(path.join(outDir, pngFileName), pngBuffer);
    pngCount++;
  }
}

console.log(`Generated ${svgCount} SVGs and ${pngCount} PNGs in ${outDir}`);
